"""The engine's ppu_recomp.h: what the boot scaffold (runtime/ppu/*.cpp) and the port's engine
sources need from the lifter's header -- ppu_context, func_entry, the guest memory accessors,
PPU_THREAD_LOCAL, PPU_FENCE -- without a single lifted prototype (the engine is built without a
lift). The lift's function table is the bound game module's (ps3emu/ps3_module.h).
(slim split, 2026-11-14)

    python -I tools/ppu_engine_header.py <out/ppu_recomp.h>

The text is the lifter's own header preamble with every lift switch off (the scaffold compiles
against either form), so it changes only when ppu_lifter.py's preamble does."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


def engine_header() -> str:
    for k in list(os.environ):          # the plain preamble: no lift switch shapes it
        if k.startswith("PPU_"):
            del os.environ[k]
    import ppu_lifter
    import ppu_fastpath
    pre = ppu_lifter.HEADER_PREAMBLE
    i, j = pre.find("\n/*@@PPU_MM@@*/\n"), pre.find("/*@@PPU_MM_END@@*/\n")
    if i >= 0 and j > i:
        pre = pre[:i] + pre[j + len("/*@@PPU_MM_END@@*/\n"):]
    pre = ppu_fastpath.header_preamble(pre)
    return ("/* GENERATED by tools/ppu_engine_header.py: the engine's view of the lifter's ppu_recomp.h\n"
            " * (no lifted prototypes; the function table is the bound game module's). */\n"
            + pre +
            "\n/* engine build (slim split): the lift's function table is the game module's */\n"
            "#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
            "extern const func_entry* ps3_mod_function_table;\n"
            "extern const uint64_t* ps3_mod_function_table_count;\n"
            "#ifdef __cplusplus\n}\n#endif\n"
            "#define function_table ps3_mod_function_table\n"
            "#define function_table_count (*ps3_mod_function_table_count)\n"
            "#define PS3_ENGINE_PPU_HEADER 1\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    text = engine_header()
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    old = open(out, encoding="utf-8").read() if os.path.isfile(out) else None
    if old != text:                      # unchanged = untouched (no rebuild of the scaffold)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


if __name__ == "__main__":
    main()
